const storedPreference = readSetting('catgpt.language', 'system');
let preference: LanguagePreference = storedPreference === 'zh-CN' || storedPreference === 'en' ? storedPreference : 'system';

export function getLanguagePreference(): LanguagePreference {
  return preference;
}

export function getLanguage(): Language {
  if (preference !== 'system') return preference;
  for (const language of navigator.languages.length ? navigator.languages : [navigator.language]) {
    if (/^zh(?:-|$)/i.test(language)) return 'zh-CN';
    if (/^en(?:-|$)/i.test(language)) return 'en';
  }
  return 'en';
}

export function setLanguagePreference(value: LanguagePreference): void {
  preference = value;
  writeSetting('catgpt.language', value);
}

export function t(key: TranslationKey, values: Readonly<Record<string, string | number>> = {}): string {
  const copy = (getLanguage() === 'zh-CN' ? zh : en)[key];
  return copy.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
